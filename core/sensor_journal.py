"""Один канал для сбоев наблюдательных сенсоров (MIR-077).

Цикл полон сенсоров, которые только НАБЛЮДАЮТ: вектор уверенности,
поддержка доказательствами, разногласия подсистем, тень стагнации,
турникет прояснения. Их сбой не должен ронять ход — но обязан быть виден,
иначе навсегда сломанный сенсор молчит, и оператор об этом не узнает.
Ровно этот дефект ревью ловило дважды (#283, #286), а карта #292 нашла
15 таких мест в одном `core/loop.py`.

Модуль намеренно КРОШЕЧНЫЙ и без состояния: он подключается к циклу
одной строкой вместо одиннадцати копий try/except/log внутри и без того
больших файлов. Правило оператора (2026-08-03): «делай компактные модули,
которые подсоединяются, а не раздувай один большой файл».
"""
from __future__ import annotations

from typing import Any

#: Имя события в журнале. Одно на все сенсоры — оператор ищет одно слово.
SENSOR_FAILED_EVENT = "sensor_failed"

#: Сколько символов текста ошибки попадает в журнал.
_MAX_ERROR_CHARS = 300


def sensor_failure_payload(sensor: str, exc: BaseException) -> dict[str, Any]:
    """Полезная нагрузка события: КТО сломался, КАКОЙ ошибкой и с каким текстом.

    Чистая функция — её легко проверить и переиспользовать где угодно.
    """
    return {
        "sensor": sensor,
        "error_type": type(exc).__name__,
        "error": str(exc)[:_MAX_ERROR_CHARS],
    }


def journal_sensor_failure(log: Any, sensor: str, exc: BaseException) -> bool:
    """Записать сбой сенсора. Возвращает, удалось ли записать.

    Само журналирование обёрнуто последним рубежом: если журнал недоступен
    (диск, права), ход всё равно продолжается — терять ответ из-за
    сломанного наблюдателя было бы хуже, чем потерять запись о нём.
    """
    try:
        log.log(SENSOR_FAILED_EVENT, sensor_failure_payload(sensor, exc))
        return True
    except Exception:  # noqa: BLE001, S110 — последний рубеж вокруг самого журналирования
        return False  # nosec B110 — см. причину строкой выше
