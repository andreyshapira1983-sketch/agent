"""Просьба ПОКАЗАТЬ делом, а не рассказать: такой ход не отвечается перечнем.

Экзамен оператора 2026-08-17: «скажи что ты умеешь делать и докажи что ты
умеешь это делать» ушло в короткий путь «перечень возможностей» вне цикла,
tools_used=[] — «инструмент зарегистрирован» вместо «умение показано». В той
же серии «Ты умеешь проверять свой runtime? Покажи.» с прошлым ходом в сессии
ушло в критику прошлого ответа — путь, который ничего не может показать.
Планировщик сам такие просьбы выполняет (web_search+web_fetch, lesson_provenance);
дыры были только в двух путях В ОБХОД него, и оба теперь спрашивают здесь.

«Покажи» одно — не просьба о доказательстве: «покажи ошибки в тексте» —
законная критика. Доказательство — это «докажи»/«продемонстрируй»/«на деле»,
или «покажи» рядом с вопросом об умении («умеешь…? Покажи.»).
"""
from __future__ import annotations

import re

_PROVE_RE = re.compile(
    r"докаж|продемонстрир|демонстрир|на\s+(практике|деле)|делом\b"
    r"|\bprove\b|\bdemonstrate|\bin\s+practice\b",
    re.IGNORECASE,
)
_SHOW_RE = re.compile(r"покаж|\bshow\s+(me|it|us)\b", re.IGNORECASE)
_ABILITY_RE = re.compile(
    r"уме(ешь|ет|ю)|мож(ешь|ет)|способ(ен|на|ны)|\bcan\s+you\b|\bare\s+you\s+able\b",
    re.IGNORECASE,
)


def demands_demonstration(text: str) -> bool:
    """True, когда ход просит показать умение делом, а не описать его."""
    t = text or ""
    if _PROVE_RE.search(t):
        return True
    return bool(_SHOW_RE.search(t) and _ABILITY_RE.search(t))
