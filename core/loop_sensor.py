"""Запись о сбое наблюдательного сенсора — один метод, и это его дом.

`core/loop_methods.py`, откуда это приехало, не было модулем: его сделал
`core/incremental_splitter.py`, резавший `core/loop.py` по бюджету строк, а не
по смыслу. Имя `methods` — это «остальное», и по нему нельзя было узнать, что
внутри лежат пять несвязанных ответственностей.

Модуль на один метод из семи строк выглядит избыточным ровно до того момента,
как посмотреть, кто его объявляет: `_sensor_failed` — самый разделяемый метод
всего раскола, его контракт заявляют пять примесей цикла. У такого нужен
адрес, а не мешок.

Смысл его в MIR-077: наблюдательный сенсор не имеет права уронить ход, но и
исчезнуть молча не имеет права тоже. Отсюда `except Exception` вокруг каждого
сенсора и эта строчка внутри — сбой не меняет ответ, но попадает в журнал.
Сама логика живёт в `core/sensor_journal.py`; здесь только делегация.
"""
from __future__ import annotations

from typing import TYPE_CHECKING, Any

from core.sensor_journal import journal_sensor_failure


class AgentLoopSensor:
    """Подмешивается в ``AgentLoop``; состояние живёт на композированном цикле.

    Члены ниже — объявления контракта хоста (``AgentLoop`` их создаёт в
    ``__init__``); присваиваний нет, поэтому во время выполнения ничего не
    создаётся и не затеняется.
    """

    if TYPE_CHECKING:  # pragma: no cover — только объявления
        log: Any

        def _durable_learning_suppressed(self, sink: str) -> bool: ...

    def _sensor_failed(self, sensor: str, exc: BaseException) -> None:
        """Тонкая делегация в `core/sensor_journal` (MIR-077).

        Логика живёт в отдельном компактном модуле — правило оператора: не
        раздувать большие файлы, а подключать маленькие.
        """
        journal_sensor_failure(self.log, sensor, exc)
