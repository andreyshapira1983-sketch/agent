"""У агента есть голос, и он должен о нём знать.

Оператор 2026-09-21 описал, чего ждёт: «если он начнёт ходить в интернет
сам, пытаться что-то доказать самому себе, а потом прийти и сказать —
слушай, вот что я узнал, я не знаю, прав ли интернет, проверь меня, — это
будет идеальный замкнутый круг».

Круг почти собран. К тому вечеру агент уже ходил в интернет без тычка (два
внешних источника в трёх последних ответах), уже спорил и дважды оказался
прав против собеседника, и задал первый за всё время вопрос — которым нашёл
настоящий дефект.

Не хватало одного: он не мог НАЧАТЬ. Файл `data/chat_outbox.jsonl` — его
голос, его читает панель оператора, — не был упомянут ни в одной строке
`core/` и `tools/`. Замер того вечера: в ящике одна строка, и та написана по
просьбе собеседника, для проверки. Агент молчал не по скромности, а потому,
что дороги наружу для него не существовало: ответить мог, заговорить нет.

Поэтому голос описан там, где агент его увидит, — в перечне инструментов
планировщика, вместе с поводами, которые стоят чужого времени. КОГДА
говорить, решает он: поручения тут нет и быть не может, иначе это снова
ответ на чужой вопрос, а не собственная речь.
"""
from __future__ import annotations

from core.planner_prompt import PLANNER_SYSTEM


def _prompt() -> str:
    return PLANNER_SYSTEM


def test_the_outbox_is_named_where_the_agent_reads() -> None:
    assert "data/chat_outbox.jsonl" in _prompt()


def test_the_prompt_says_it_is_how_to_speak_first() -> None:
    text = _prompt()
    assert "заговорить с человеком ПЕРВЫМ" in text
    assert "панель оператора" in text


def test_the_reasons_are_offered_not_ordered() -> None:
    """Поводы названы, но выбор оставлен агенту — иначе это не его речь."""
    text = _prompt()
    assert "решаешь ты" in text
    assert "противоречит" in text, "повод: находка спорит с его же выводами"


def test_records_about_itself_still_go_to_the_registry() -> None:
    """Голос — не свалка: находки о себе идут туда, где их читает цикл."""
    text = _prompt()
    assert "data/self_improvement_issues.jsonl" in text
    assert "КАЖДОГО цикла" in text
