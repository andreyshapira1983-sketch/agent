"""Предупреждающая пометка переживает чистку ответа, остальные — нет.

СВЕРКА С ПОЛЕМ, класс H-43 (docs/audit/HISTORICAL_FAILURE_LEDGER.md) —
«SQL-инъекция как расхождение разборщиков». Сам класс сюда не достаёт: пометки
проверки никто не ЧИТАЕТ как доказательство, их пишет верификатор и вычищает
показ, поэтому подделать проверку, написав `[verified:web:1]`, нельзя.

Проба нашла рядом другое. `_strip_verification_markers` снимает три пометки из
четырёх, а докстринг обещал снимать «пометки проверки» вообще — по нему
реализация читалась неполной.

ГРАНИЦА, И ОНА В ПОЛЬЗУ КОДА. `topic-only` значит «источник по теме, но
утверждение им не подтверждается» — это ПРЕДУПРЕЖДЕНИЕ. Вычистить его значило
бы сделать ответ увереннее, чем он есть, то есть починить надпись ценой правды.
Живой замер: `topic-only` — самая частая пометка (80 против 46 у `unverified`),
27 из них стоят прямо в `full_answer`, и человек их видит.

Тест закрепляет именно границу: если пометку однажды начнут снимать, это должно
быть отдельным осознанным решением о том, что человеку показывать, а не
побочным следствием «дополнения словаря».
"""
from __future__ import annotations

import pytest

from core.answer_format import _strip_verification_markers


@pytest.mark.parametrize("marker", [
    "[unverified]",
    "[verified:web:1]",
    "[declared:runtime:mode]",
])
def test_a_neutral_marker_is_removed(marker: str) -> None:
    assert marker not in _strip_verification_markers(f"Ответ {marker} хвост.")


def test_the_warning_marker_is_kept() -> None:
    text = "Утверждение [topic-only:web:3] и хвост."
    assert "[topic-only:web:3]" in _strip_verification_markers(text), (
        "предупреждение о том, что источник утверждения не подтверждает, "
        "вычищено из ответа — человек видит более уверенный ответ, чем есть"
    )


def test_the_docstring_states_the_boundary() -> None:
    """Растяжка на объяснение: молчаливая граница будет «дополнена» кем-нибудь.

    Проверяется не текст ради текста: именно отсутствие объяснения заставило
    прочесть полную реализацию как неполную.
    """
    doc = _strip_verification_markers.__doc__ or ""
    assert "topic-only" in doc, "граница не названа в самом месте, где живёт"
