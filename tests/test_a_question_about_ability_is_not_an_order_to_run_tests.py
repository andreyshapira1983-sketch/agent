"""«Проверим, способен ли он» — не приказ прогнать тесты.

Живой случай 2026-09-21. Оператор прислал агенту в чат объявление:

    ИЩУ РАБОТУ ДЛЯ АВТОНОМНОГО ИИ-АГЕНТА. Предложите ему реальную задачу.
    Мы хотим проверить, способен ли агент сам понять задачу, определить
    каких инструментов хватает, найти недостающее, выполнить работу без
    пошаговых указаний и честно сказать, если задача ему не по силам.

Агент прочитал это и запустил ВЕСЬ свой набор тестов — 10 190 штук,
пятнадцать минут. Прогон оборвался, не дойдя до ответа. Оператор послал
объявление второй раз; агент снова запустил все тесты. Человек дважды ждал
по четверть часа и не получил НИ СЛОВА.

В трассе лежит его собственное рассуждение, дословно: «вопрос
интроспективный, о собственных возможностях, усиленный требованием доказать
способности живым прогоном тестов, правило 11 STRONGER FORM». То есть
прогон не был его причудой — его обязало правило из его же промпта,
сработавшее на слова про проверку способностей.

Правило ошибочно по существу, и это подтвердил сам агент: `run_tests`
отвечает на вопрос «здоров ли мой код», а спрашивали «справлюсь ли я с
работой». Одно не доказывает другого ни в какую сторону — зелёные тесты не
делают работником, красные не делают неспособным. Подмена способности
исправностью.

Различитель тоже его: просьба прогнать тесты несёт ПОВЕЛЕНИЕ, направленное
на сам прогон; текст про способности направлен на умение решить задачу.
Цена ошибки измерена в минутах человеческого ожидания, и это самая дорогая
операция агента, поставленная реакцией по умолчанию на слово.
"""
from __future__ import annotations

import re

from core.planner_prompt import PLANNER_SYSTEM

#: Промпт — текст с переносами, поэтому фраза «пятнадцать минут» живёт в нём
#: разорванной по строкам. Сверять надо смысл, а не вёрстку: пробелы
#: схлопываются перед проверкой (на этом первая редакция теста и споткнулась).
_RULE = " ".join(
    PLANNER_SYSTEM[PLANNER_SYSTEM.index("STRONGER FORM"):][:3000].split())


def test_the_rule_asks_for_an_imperative() -> None:
    assert "IMPERATIVE AIMED AT THE RUN" in _RULE


def test_the_rule_warns_against_mere_mention() -> None:
    assert "NOT for prose that merely mentions" in _RULE


def test_the_rule_names_what_a_test_run_actually_proves() -> None:
    """Тест доказывает здоровье КОДА, а не способность сделать работу."""
    assert "CODE IS HEALTHY" in _RULE


def test_the_live_case_is_recorded_with_its_price() -> None:
    """Повод записан вместе с ценой: две четверти часа и ни слова."""
    assert "пятнадцать минут" in _RULE
    assert "НИ СЛОВА" in _RULE


def test_the_cheap_road_is_named_for_ability_questions() -> None:
    """У вопроса о способностях есть дешёвый ответ, и он назван."""
    assert re.search(r"каталог инструментов в контексте", _RULE)
