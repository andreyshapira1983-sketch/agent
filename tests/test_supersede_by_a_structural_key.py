"""Замена устаревшего вывода — по структурному ключу, не по похожести.

Замер 2026-09-23 на 217 живых записях: `superseded_by` не срабатывал НИ РАЗУ.
Сравнение шло по строке вопроса дословно, а текст цели пишет модель и
формулирует заново каждый цикл — вопросы об одном расходились с 82-го знака:
«найти раздел О лексическом анализе» против «найти раздел ПРО лексический
анализ». В памяти осели 6 записей об одном разделе одной книги, 4 об одном
сообщении об ошибке, 3 об одном разборе случая.

ПРИНЦИП взят из литературы, не придуман: определение устаревания обязано быть
СТРУКТУРНЫМ — ключ (предмет, отношение) и точное равенство, без мер сходства.
Измерено, что противоречие в среднем ПОХОЖЕЕ на исходник, чем настоящий
пересказ того же самого (подмена значения — меньшая правка, чем
переформулировка), и распределения перекрываются так, что предельная точность
при ЛЮБОМ пороге сходства равна 0.67 (arXiv 2606.26511). Первая редакция этой
правки была именно порогом по пересечению слов, и собственная проверка её
отвергла: она склеила «лексический анализ» и «синтаксический разбор» в одной
книге, то есть затёрла бы верный вывод чужим. Этот случай заперт тестом ниже.

ЧЕСТНО о границе: извлечение ключа здесь — регулярное выражение по прозе, и
это НЕ то, как делают в эталоне. Zep/Graphiti (arXiv 2501.13956) извлекает
сущности и связи МОДЕЛЬЮ при приёме, кладёт их узлами и рёбрами графа и даёт
каждому ребру интервал действия (t_valid, t_invalid), помечая устаревшее
заменённым по времени. Это отдельная большая работа; здесь — узкая починка
того, что не работало вовсе.
"""
from __future__ import annotations

from typing import ClassVar

import pytest

from core.learned_conclusion import question_key, same_question, superseded_by

_MOG = "knowledge_library/cs/txt/Mogensen_BasicsOfCompilerDesign.txt"
_ERI = "knowledge_library/cs/txt/Erickson_Algorithms.txt"


@pytest.mark.parametrize(
    ("a", "b", "same", "why"),
    [
        (f"В книге {_MOG} найти раздел о лексическом анализе (lexer/tokenizer)",
         f"Прочитать в {_MOG} раздел про лексический анализ (lexer/tokenizer)",
         True, "переформулировка того же предмета"),
        (f"В книге {_MOG} найти раздел о лексическом анализе (lexer/tokenizer)",
         f"В книге {_MOG} найти раздел о синтаксическом разборе (parser)",
         False, "ДРУГОЙ раздел той же книги — на этом умерла первая редакция"),
        (f"В книге {_MOG} найти раздел про лексический анализ (lexer/tokenizer)",
         f"Прочитать в {_ERI} раздел (lexer/tokenizer)",
         False, "то же отношение, ДРУГАЯ книга"),
        ("Прочитать data/charter_decisions.jsonl и выписать записи",
         "Разобрать случай в data/charter_decisions.jsonl",
         False, "отношения нет — ключа нет, записи не трогаются"),
        ("Найти код, который формирует 'goal first: the goal names ... as the work'",
         "Найти файл, где формируется сообщение 'goal first: the goal names ... as the work'",
         True, "отношение в кавычках, путь не назван"),
    ],
)
def test_the_key_is_structural(a: str, b: str, same: bool, why: str) -> None:
    assert same_question(a, b) is same, why


def test_no_relation_means_no_key() -> None:
    """Нет названного отношения — нет ключа, и это НАРОЧНО.

    Иначе ключ вырождается в один путь и склеивает любые два вопроса об одном
    файле: проверено на `data/charter_decisions.jsonl`, где так слились разбор
    случая и выписка записей. Цена ошибки несимметрична — недосклеить значит
    оставить лишнюю запись, пересклеить значит стереть верное знание.
    """
    assert question_key("Прочитать файл и выписать записи") is None
    assert question_key("") is None
    assert question_key("найти раздел (lexer/tokenizer)") is not None


def test_an_identical_conclusion_is_still_refused_as_a_duplicate() -> None:
    """Прежняя защита от точного дубля не ослаблена."""
    class _R:
        tags: ClassVar[list[str]] = ["fact", "conclusion"]
        content = ("Вопрос: найти раздел (lexer/tokenizer)\n"
                   "Вывод: раздел 2.1\nИсточники: file:x.txt")
    new = ("Вопрос: прочитать раздел (lexer/tokenizer)\n"
           "Вывод: раздел 2.1\nИсточники: file:x.txt")
    old, dup = superseded_by(new, [_R()])
    assert dup is True, "тот же вывод по тому же предмету — дубль"
    assert old == []


def test_a_different_conclusion_supersedes_the_old_one() -> None:
    """Исправленный вывод ЗАМЕНЯЕТ прежний, а не отвергается как дубль.

    Правка 2026-09-19 сделана против навсегда закреплённой ошибки «страница
    326»: защита от дублей отвергала исправление, потому что оно почти
    дословно совпадало со старым.
    """
    class _R:
        tags: ClassVar[list[str]] = ["fact", "conclusion"]
        content = ("Вопрос: найти раздел (lexer/tokenizer)\n"
                   "Вывод: страница 326\nИсточники: file:x.txt")
    new = ("Вопрос: прочитать раздел (lexer/tokenizer)\n"
           "Вывод: страница 327\nИсточники: file:x.txt")
    old, dup = superseded_by(new, [_R()])
    assert dup is False
    assert len(old) == 1, "прежний вывод о том же предмете обязан замениться"
