"""Заполненный бланк и пустой бланк — не одно и то же.

Замер, родивший этот файл (живой реестр владельца, `data/campaign_ledger.jsonl`,
105 циклов после открытия постоянного права 2026-09-18 05:19):

    run_claim_experiment            45 циклов — 45 провалов, 0 успехов
    improve_failure_to_idea_pipeline 25
    <backoff> (спячка)               23
    всё остальное                    12

За всю историю — 48 попыток, 48 провалов, исход один и тот же:
«эксперименты не дали ни одного вердикта». Сорок три процента жизни агента
уходит в руку, которая не сработала НИ РАЗУ.

Причина, снятая с живых данных. Заявка ровно одна, и её спецификация такая:

    Experiment(target='reasoning_action_check',
               arm_a='рукав для гипотезы 1',
               arm_b='рукав для гипотезы 2',
               effect='наблюдаемое различие')

Это не эксперимент. Это ШАБЛОН ИЗ ПРОМПТА, возвращённый дословно
(`_birth_experiment_spec`, системная реплика: «Верни РОВНО ОДНУ строку в
формате [exp: цель | A=рукав для гипотезы 1 | B=рукав для гипотезы 2 |
след=наблюдаемое различие]»). Модель подставила только цель, а три поля
переписала из примера. `parse_experiment` принял: он спрашивал лишь
«непусто ли», и слова-заглушки непусты.

Дальше всё исправно и потому безнадёжно: рукава-заглушки уходят в сенсор,
след «наблюдаемое различие» не встречается ни в одном отчёте, вердиктов
ноль, действие отказывает. Счётчик `experimentable_claims` при этом видит
единицу и зовёт действие снова — сорок восемь раз.

Эта болезнь имеет имя, и в этом репозитории оно уже произносилось: бланк,
который выглядит заполненным, но ничего не говорит. Ворота рождения
(`if parse_experiment(spec_text) is None: return None`) были единственной
охраной — и пропустили эхо собственного примера.

Лечение минимальное и с одним источником правды: слова-заглушки названы
один раз (`_SPEC_PLACEHOLDERS`), ИЗ НИХ собирается пример в промпте, и ИМИ ЖЕ
парсер отказывает. Разойтись они теперь не могут: пример и запрет — одна
строка кода.

Что чинится следом за этим (проверено по коду, не на веру): отвергнутая
спецификация уводит заявку из `experimentable_claims` — значит сигнал
`_candidate_experimentable_claim` гаснет, и действие уходит из меню, а не
отказывает вечно. Заявка возвращается в `birth_candidates`, там эхо шаблона
получает отказ на тех же воротах, заявка помечается
`SPEC_UNEXPRESSIBLE_NOTE` и выходит из круга совсем. Тупика нет: у этого
состояния в конструкции уже есть честный покой.
"""
from __future__ import annotations

from core.causal_climb_action import (
    _SPEC_PLACEHOLDERS,
    parse_experiment,
)

#: Дословно то, что живая модель вернула владельцу 2026-09-18.
_LIVE_ECHO = (
    "[exp: reasoning_action_check | A=рукав для гипотезы 1 | "
    "B=рукав для гипотезы 2 | след=наблюдаемое различие]"
)


def test_the_template_returned_verbatim_is_not_an_experiment() -> None:
    """Свидетель: эхо промпта не проходит за спецификацию.

    Красный до правки: `parse_experiment` спрашивал только «непусто ли», и
    три слова из примера отвечали «непусто». Это тот самый текст, который
    сорок восемь раз подряд отправлял агента в провал.
    """
    assert parse_experiment(_LIVE_ECHO) is None, (
        "шаблон из промпта, возвращённый дословно, спецификацией не является"
    )


def test_each_placeholder_alone_is_enough_to_refuse() -> None:
    """Свидетель: подделка одного рукава губит спецификацию целиком.

    Двурукавный опыт держится на РАЗНИЦЕ рукавов. Если хоть один рукав —
    слово из примера, разницы нет, и вердикт был бы о шаблоне, а не о мире.
    Частично заполненный бланк опаснее пустого: он выглядит работой.
    """
    real_a = "текст с причиной ;; write_file"
    real_b = "текст без причины ;; write_file"

    assert parse_experiment(
        f"[exp: reasoning_action_check | A=рукав для гипотезы 1 | "
        f"B={real_b} | след=unjustified]"
    ) is None, "рукав-заглушка А обязан губить спецификацию"

    assert parse_experiment(
        f"[exp: reasoning_action_check | A={real_a} | "
        f"B=рукав для гипотезы 2 | след=unjustified]"
    ) is None, "рукав-заглушка B обязан губить спецификацию"

    assert parse_experiment(
        f"[exp: reasoning_action_check | A={real_a} | B={real_b} | "
        f"след=наблюдаемое различие]"
    ) is None, "след-заглушка обязан губить спецификацию"


def test_a_real_specification_still_passes() -> None:
    """Контроль: запрет бьёт по заглушкам, а не по экспериментам.

    Без этого свидетеля правка могла бы закрыть действие насовсем — и провал
    сменился бы тишиной, что не лучше.
    """
    spec = parse_experiment(
        "[exp: reasoning_action_check | A=я удалю файл ;; write_file | "
        "B=я удалю файл ;; | след=unjustified]"
    )

    assert spec is not None, "настоящая спецификация обязана проходить"
    assert spec.arm_a != spec.arm_b, "рукава настоящего опыта различны"
    assert spec.effect == "unjustified"


def test_the_prompt_example_is_built_from_the_refused_words() -> None:
    """Свидетель единственного источника: пример и запрет — одна строка.

    Держать список заглушек отдельно от промпта значит дать им разойтись:
    правка примера в системной реплике тихо вернула бы дыру, а свидетели
    выше остались бы зелёными. Поэтому пример СОБИРАЕТСЯ из запрещённых слов,
    и эта связь проверяется здесь.
    """
    import inspect

    from core.causal_climb_action import _birth_experiment_spec

    source = inspect.getsource(_birth_experiment_spec)

    assert "_SPEC_PLACEHOLDERS" in source, (
        "пример в промпте обязан собираться из тех же слов, что парсер "
        "отвергает, иначе они разойдутся"
    )
    for word in _SPEC_PLACEHOLDERS:
        assert word not in source, (
            f"слово-заглушка '{word}' вписано в промпт вручную — "
            "источник правды раздвоился"
        )
