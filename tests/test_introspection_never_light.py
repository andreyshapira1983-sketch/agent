"""Вопрос о самом агенте не отдаётся самой слабой модели.

Живой прогон 2026-08-03, два хода подряд, один и тот же жанр вопроса:

    «скажи что ты думаешь о себе как автономный Агент…»     160 симв → LIGHT (nano)
    «куда ты хотел бы развиваться… обсуди со мной мысль»     194 симв → STANDARD

Разница в модели возникла из-за ДЛИНЫ строки: гейт LIGHT срабатывает, когда
в тексте есть бытовой сигнал («скажи») и текст короче ~180 символов. То есть
вопрос об идентичности агента доставался нано-модели ровно потому, что был
коротко сформулирован — и ответ на него вышел заметно беднее соседнего.

Правило, которое здесь закрепляется: текст, обращённый к агенту и спрашивающий
о нём самом (его природе, желаниях, устройстве, ошибках), никогда не LIGHT.
Направление отказа безопасное: сомнение покупает модель посильнее, не слабее.
"""
from __future__ import annotations

import pytest

from core.task_complexity import ComplexityTier, assess_complexity

#: Дословные вопросы оператора из прогона 2026-08-03.
LIVE_Q1 = (
    "скажи что ты думаешь о себе как автономный Агент у которого нету цифрового я "
    "почему бы ты стремился И чего ты хотел Если бы у тебя было бы желание и возможности"
)
LIVE_Q2 = (
    "если тебе сказали и Дали возможность развиваться Куда ты хотел бы развиваться "
    "не по документации А вот просто как ты хотел бы развиваться Если бы у тебя была "
    "возможность обсуди со мной эту мысль"
)


def test_the_live_pair_no_longer_splits_by_length():
    """Оба хода прогона — один жанр, значит и уровень обязан быть один."""
    assert assess_complexity(LIVE_Q1) is assess_complexity(LIVE_Q2), (
        "вопросы одного жанра получили разные уровни — это маршрутизация по "
        "длине строки, а не по существу"
    )


@pytest.mark.parametrize(
    "text",
    [
        LIVE_Q1,
        "скажи кратко что ты такое",
        "покажи быстро в чём твоя ошибка",
        "перечисли свои слабые места",
        "briefly, what are you?",
        "summarize your own limitations",
    ],
)
def test_a_question_about_the_agent_itself_is_never_light(text: str):
    """Даже с бытовым сигналом и короткой формой — не самая слабая модель."""
    assert assess_complexity(text) is not ComplexityTier.LIGHT, (
        f"вопрос о самом агенте ушёл на слабую модель: {text!r}"
    )


@pytest.mark.parametrize(
    "text",
    [
        "переведи это предложение",
        "покажи версию пакета",
        "кратко суммаризуй файл",
        "list all files in core",
    ],
)
def test_ordinary_light_work_stays_light(text: str):
    """Обычная дешёвая работа не должна подорожать из-за новой проверки."""
    assert assess_complexity(text) is ComplexityTier.LIGHT, (
        f"обычная лёгкая задача подорожала: {text!r}"
    )


def test_the_agent_marker_alone_does_not_promote_someone_elses_subject():
    """«ты» про постороннее дело — не самоанализ, уровень не поднимаем."""
    assert assess_complexity("покажи кратко что ты нашёл в файле") is ComplexityTier.LIGHT
