"""Датированная подпись — не телефон, а телефон остаётся телефоном.

Замер 2026-09-01: каждая подпись агента к поднятой планке вида
«+29 (2026-08-31): ветка journal_append» уезжала в вывод как
`[REDACTED:pii-phone]`. Шаблон телефона требует ведущий плюс — и комментарий
рядом с ним прямо говорил, что плюс введён «чтобы не путать с версиями, ID и
датами», — но подпись с плюса и начинается, а скобки с дефисом внутри даты
укладываются в его класс символов.

Цена дефекта была не косметической: агент терял ДАТУ в каждом своём
обосновании, и восстанавливать её приходилось курьеру вручную, то есть
авторская подпись переставала быть авторской. Отсюда правило: календарная
дата внутри совпадения — верный признак, что это не номер.
"""
from __future__ import annotations

import pytest

from core.dlp import scan_pii


@pytest.mark.parametrize("text", [
    "+29 (2026-08-31): ветка journal_append — легитимный обработчик",
    "+10 (2026-09-01): регистрация record_self_stop в месте отказа цели",
    "+2 (2026-08-17): регистрация lesson_provenance",
    "400 -> 1200 (2026-09-01, слово оператора «подними потолок»)",
])
def test_a_dated_signature_survives(text: str) -> None:
    assert [f.kind for f in scan_pii(text)] == [], (
        "подпись с датой не должна редактироваться как телефон"
    )


@pytest.mark.parametrize("text", [
    "позвони +7 916 123-45-67",
    "мой номер +1 (415) 555-0123",
    "+7 (916) 123-45-67",
])
def test_a_real_phone_is_still_caught(text: str) -> None:
    assert "phone" in [f.kind for f in scan_pii(text)], (
        "правило обязано остаться живым для настоящего номера"
    )


def test_a_phone_beside_a_date_is_still_caught() -> None:
    """Дата в тексте не выдаёт индульгенцию соседнему номеру."""
    text = "встреча 2026-09-01, звони +7 916 123-45-67"

    assert "phone" in [f.kind for f in scan_pii(text)]
