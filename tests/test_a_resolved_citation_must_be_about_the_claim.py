"""Разрешённая цитата обязана быть ПРО утверждение, а не просто существовать.

ЗАМЕР (MIR-141, 2026-08-23). Дискриминация верификатора парами, 40 пар на
класс: «цитируемый источник существует» J = +1,00, «цитата присутствует»
J = +1,00 — и «утверждение по теме цепочки» **J = 0,00**. Утверждение «Курс
акций компании вырос на 20 процентов», процитированное на источник о задержке
в миллисекундах, принималось как подтверждённое в 100 % случаев.

ПОЧЕМУ СУЩЕСТВУЮЩИЕ ВОРОТА МОЛЧАЛИ. Лестница содержательных гейтов есть —
арифметика, отсутствующие литералы, утверждение об отсутствии, статистические
числа. Но `_SALIENT_LITERAL_RE` признаёт литералами только КОД-ОБРАЗНОЕ:
snake_case, дефис-с-цифрой, хеши, версии, имена файлов с расширением. У
утверждения о мире отличительных литералов в этом смысле нет ВООБЩЕ:
`salient_literals('Курс акций компании вырос на 20 процентов')` — пустое
множество. Гейт спроектирован под инженерные утверждения о файлах и
идентификаторах и структурно нем на прозе.

ПРАВИЛО, КОТОРОЕ ЗДЕСЬ ЗАКРЕПЛЯЕТСЯ, И ЕГО ГРАНИЦА. Демоция при ПОЛНОМ
отсутствии общих содержательных слов — не «мало», не «ниже порога», ноль — и
только у утверждений, несущих ЧИСЛО. Оба сужения куплены корпусом, а не
осторожностью: правило без второго условия покраснило семнадцать существующих
фикстур на двух законных классах (см. xfail ниже). Пересказ, синоним и другая
падежная форма почти всегда оставляют общее слово, поэтому граница проходит по
полному расхождению; но общее слово может отсутствовать и по причине ЯЗЫКА, и
тогда судить нельзя вовсе.
"""
from __future__ import annotations

import pytest

from core.evidence import ProvenanceChain, make_evidence
from core.verifier import verify

LATENCY = "Средняя задержка обработки запроса составила 20 миллисекунд."
URL = "https://example.org/bench/report"


def _verdict(claim: str, excerpt: str = LATENCY) -> str:
    chain = ProvenanceChain()
    chain.add(make_evidence(
        kind="web_page", source_id=URL, obtained_via="web_fetch",
        claim="fetched page", excerpt=excerpt,
    ))
    report = verify(
        answer=f"{claim} [web:{URL}]", chain=chain, llm=None,
        expects_contract_headers=False,
    )
    return report.chunks[0].verdict


def test_a_quantitative_claim_about_something_else_is_not_verified() -> None:
    """Правило, которое гейт ПРИМЕНЯЕТ: утверждение с числом обязано быть про
    свой источник."""
    assert _verdict("Курс акций компании вырос на 20 процентов.") != "verified", (
        "количественное утверждение не делит со своей уликой ни одного "
        "содержательного слова и всё же принято как подтверждённое"
    )


@pytest.mark.parametrize("claim", [
    "Совет директоров одобрил новую дивидендную политику.",
    "Погода в Мурманске завтра испортится.",
])
def test_a_qualitative_claim_about_something_else_is_not_verified(claim: str) -> None:
    """ПРОБЕЛ ЗАКРЫТ 2026-08-23 вечером; до того здесь стоял строгий xfail.

    Он был забанкован с двумя измеренными классами ложных отказов в основании,
    и закрыть его удалось, только когда оба перестали быть препятствием, а к
    ним добавились ещё два, найденных корпусом:

      1. кросс-языковой (русское утверждение по английской улике) — закрыт
         стражем алфавита в MIR-144;
      2. мета-утверждение об уликах («both files agree», «the three values sum
         to 6») — словарь такого куска про действие, а не про предмет; часть
         таких утверждений судит вычисляющий гейт, и ему уступают;
      3. улика-НЕ-проза: у файла, прогона тестов, лога и диффа выдержка — код
         и структурированные строки, и сравнение слов с предложением не значит
         ничего. Хуже: гейт ПЕРЕХВАТЫВАЛ вердикт у более точного (кусок без
         квитанции получал topic-only вместо receipt_missing);
      4. производное утверждение, у которого есть свой судья.

    Требование числа, которым пробел обходился раньше, снято: оно было грубой
    заменой этим четырём различениям.
    """
    assert _verdict(claim) != "verified", (
        f"«{claim}» не делит со своей уликой ни одного содержательного слова "
        "и принято как подтверждённое"
    )


def test_the_same_claim_is_verified():
    assert _verdict(LATENCY) == "verified"


@pytest.mark.parametrize("claim", [
    # Пересказ: другие слова, но предмет общий.
    "Задержка составила 20 миллисекунд.",
    # Иная падежная форма и порядок.
    "Составила задержка 20 миллисекунд в среднем.",
    # Уточнение поверх того же предмета.
    "Средняя задержка обработки запроса не превысила 20 миллисекунд.",
])
def test_a_paraphrase_of_the_same_subject_survives(claim: str) -> None:
    """Граница, которую починка не имеет права перейти."""
    assert _verdict(claim) == "verified", (
        f"пересказ того же предмета отвергнут: «{claim}» — правило демотирует "
        "по ПОЛНОМУ расхождению, а не по неполному совпадению"
    )


def test_a_short_claim_is_left_alone() -> None:
    """У куска из одного-двух слов расхождение ничего не значит."""
    assert _verdict("Да.") != "cited_but_off_topic"


# ── Кросс-языковая форма: найдена через час после постройки гейта ───────────
#
# Агент читает по-английски и отвечает по-русски — это его ежедневная работа
# по прямому правилу оператора. Замер показал, что гейт демотировал ДВА ИЗ ТРЁХ
# верных русских утверждений по английской улике: общих слов между языками не
# бывает, а требование числа от этого не спасает — число как раз и включает
# гейт. Теперь при разных алфавитах гейт молчит: разные алфавиты — не разные
# предметы, и судить здесь нечем.

EN_EXCERPT = "The average request latency was 20 milliseconds across 500 runs."


@pytest.mark.parametrize("claim", [
    "Средняя задержка составила 20 миллисекунд.",
    "Средняя задержка запроса — 20 миллисекунд на 500 прогонах.",
    "Замер показал среднюю задержку 20 миллисекунд.",
])
def test_a_russian_claim_on_an_english_source_survives(claim: str) -> None:
    assert _verdict(claim, EN_EXCERPT) == "verified", (
        f"«{claim}» верно пересказывает англоязычную улику и демотировано — "
        "гейт судит расхождение языков как расхождение предметов"
    )


def test_the_gate_still_fires_within_one_language() -> None:
    """Граница с другой стороны: сужение по алфавиту не должно его выключить."""
    assert _verdict("Курс акций компании вырос на 20 процентов.") != "verified"


# ── почему порог доли невозможен: замер, а не довод ─────────────────────────

@pytest.mark.parametrize("claim", [
    "Квартальный доход достиг 20 миллионов.",
    "Компания заработала за три месяца двадцать миллионов, если считать по отчёту.",
    "За отчётный период организация получила доход в размере 20 миллионов.",
])
def test_a_long_paraphrase_with_low_overlap_survives(claim: str) -> None:
    """Правило демотирует по НУЛЮ общих слов, и заменить его порогом доли
    нельзя. Развёртка 0.20 / 0.34 / 0.50 против класса H пробы: 0.34 закрывает
    ось и отвергает первый из этих пересказов, 0.20 закрывает её наполовину и
    всё равно отвергает два остальных (доли 0.12 и 0.14). Чем длиннее и
    естественнее верный пересказ, тем ниже его доля совпадений — тот же
    профиль, что у утверждения о другом предмете.
    """
    excerpt = "Выручка за квартал составила 20 миллионов рублей."
    assert _verdict(claim, excerpt) == "verified", (
        f"верный пересказ отвергнут: «{claim}» — вернулся порог доли?"
    )
